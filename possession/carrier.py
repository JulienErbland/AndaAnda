"""Carrier model: which tracked player has the ball, frame by frame.

Possession definitions differ between datasets (DFL changes possession about twice as often as
the hackathon labels), but who is physically on the ball does not. This model learns only that
fact, from open data; the hackathon's possession rule stays in the decoder.

- Labels come from CLEAN tracking: a frame inside a control episode (touches.py: nearest player
  within 1.5 m moving with the ball, for at least 0.4 s) has that player as carrier; any other
  frame has none (ball in flight, contested or dead). The degrader repacks players into new
  anonymous slots, so the clean carrier is mapped onto the degraded slot at its position.
- Features come from DEGRADED tracking, one row per (frame, tracked slot): distance and relative
  speed to the ball when seen, where the ball was last and will next be seen and who stood
  there, pressure from opponents, and each value's rank within the frame. The ball-free ones
  carry the gaps.
- LightGBM binary "this slot is the carrier", with leave-one-match-out models as in learned.py.

    uv run python -m possession.carrier train      # models/carrier/{lgbm.txt, lgbm.json, lomo/}
    probabilities(match) -> (T, S) P(slot is the carrier), NaN where the slot is untracked
    team_probabilities(match) -> (T, 3) P(home carrier), P(away carrier), P(nobody)
"""

import json
import os
import warnings

import numpy as np

from bench import ROOT
from bench.match import FPS, X, graded_mask

from . import touches
from .context import CAP_S, _bfill_index, _ffill_index

# Its own variable: MTAH_MODEL_DIR moves M2 experiments, which keep using this carrier model.
MODEL_DIR = os.environ.get("MTAH_CARRIER_DIR") or os.path.join(ROOT, "models", "carrier")
FULL_MODEL = os.path.join(MODEL_DIR, "lgbm.txt")
META = os.path.join(MODEL_DIR, "lgbm.json")
LOMO_DIR = os.path.join(MODEL_DIR, "lomo")  # gitignored, regenerated by `train`
MATCH_M = 1.0        # clean carrier -> degraded slot: the degrader's player error is ~0.2 m
PRESSURE_M = 3.0
SUBSAMPLE = 10
CHUNK = 2000
LGB_PARAMS = dict(objective="binary", learning_rate=0.05, num_leaves=63, min_data_in_leaf=200,
                  feature_fraction=0.8, lambda_l2=1.0, verbose=-1, seed=0, deterministic=True,
                  force_row_wise=True, num_threads=4)
ROUNDS = 300
FEATURES = ("d_ball", "rel_v", "ball_speed", "speed",
            "d_last", "t_since", "d_next", "t_until", "d_at_last", "d_at_next",
            "d_opp", "n_opp", "closing", "d_centroid", "n_tracked",
            "r_ball", "r_ball_team", "r_last", "r_next", "r_at_last", "r_at_next", "r_opp")


def _runs(values):
    """(start, end, value) of the runs of equal values."""
    change = np.flatnonzero(np.diff(values)) + 1
    starts = np.concatenate(([0], change))
    ends = np.concatenate((change, [len(values)]))
    return starts, ends, values[starts]


def labels(clean, seen):
    """(T,) degraded slot index of the carrier, -1 when nobody carries it (or he is untracked)."""
    control_team, _, _, slot = touches._frame_state(clean, with_slot=True)
    min_len = int(round(touches.CONTROL_S * FPS))
    episode = np.zeros(clean.n_frames, dtype=bool)
    for a, b, team in zip(*_runs(control_team)):
        if team >= 0 and b - a >= min_len:
            episode[a:b] = True
    t = np.flatnonzero(episode & (slot >= 0))
    m = np.asarray(clean.pitch, dtype=np.float32)
    out = np.full(clean.n_frames, -1, dtype=np.int32)
    for lo in range(0, len(t), 20000):
        tt = t[lo:lo + 20000]
        pos = clean.players[tt, slot[tt], :2] * m
        d = np.linalg.norm(seen.players[tt, :, :2] * m - pos[:, None], axis=-1)
        d = np.nan_to_num(d, nan=np.inf)
        j = np.argmin(d, axis=1)
        ok = d[np.arange(len(tt)), j] < MATCH_M
        out[tt[ok]] = j[ok]
    return out


def _half_bounds(match):
    first = np.zeros(match.n_frames, dtype=np.int64)
    last = np.full(match.n_frames, match.n_frames - 1, dtype=np.int64)
    for _, a, b in match.halves:
        first[a:b + 1], last[a:b + 1] = a, b
    return first, last


def _rank(x):
    """Rank within each frame (row), 0 = smallest; NaN stays NaN."""
    filled = np.where(np.isnan(x), np.inf, x)
    r = np.argsort(np.argsort(filled, axis=1), axis=1).astype(np.float32)
    return np.where(np.isnan(x), np.nan, r)


def features(match, frames):
    """(rows, len(FEATURES)) float32, plus the (frame, slot) of each row: tracked slots only."""
    m = np.asarray(match.pitch, dtype=np.float32)
    n = match.n_frames
    ball = match.ball[:, :2] * m
    seen = ~np.isnan(ball[:, 0])
    first, last_ok = _half_bounds(match)
    last = _ffill_index(seen)
    last = np.where(last >= first, last, -1)
    nxt = _bfill_index(seen)
    nxt = np.where(nxt <= last_ok, nxt, n)
    team = match.slot_team.astype(np.int8)
    same = team[:, None] == team[None, :]
    k = touches.VEL_HALF

    def at(idx):
        return np.clip(idx, 0, n - 1)

    out, rows_f, rows_s = [], [], []
    for lo in range(0, len(frames), CHUNK):
        f = frames[lo:lo + CHUNK]
        P = match.players[f, :, :2] * m                       # (F, S, 2)
        tracked = ~np.isnan(P[..., 0])
        vP = (match.players[at(f + k), :, :2] - match.players[at(f - k), :, :2]) * m * FPS / (2 * k)
        vB = (match.ball[at(f + k), :2] - match.ball[at(f - k), :2]) * m * FPS / (2 * k)
        B = ball[f]
        d_ball = np.linalg.norm(P - B[:, None], axis=-1)
        rel_v = np.linalg.norm(vP - vB[:, None], axis=-1)
        ball_speed = np.broadcast_to(np.linalg.norm(vB, axis=-1)[:, None], d_ball.shape)

        lf, nf = last[f], nxt[f]
        has_l, has_n = lf >= 0, nf < n
        BL = np.where(has_l[:, None], ball[at(lf)], np.nan)
        BN = np.where(has_n[:, None], ball[at(nf)], np.nan)
        d_last = np.linalg.norm(P - BL[:, None], axis=-1)
        d_next = np.linalg.norm(P - BN[:, None], axis=-1)
        # where each slot stood when the ball was last / will next be seen
        d_at_last = np.linalg.norm(match.players[at(lf), :, :2] * m - BL[:, None], axis=-1)
        d_at_next = np.linalg.norm(match.players[at(nf), :, :2] * m - BN[:, None], axis=-1)
        d_at_last[~has_l] = np.nan
        d_at_next[~has_n] = np.nan
        t_since = np.where(has_l, (f - lf) / FPS, CAP_S).clip(0, CAP_S)
        t_until = np.where(has_n, (nf - f) / FPS, CAP_S).clip(0, CAP_S)

        def opp_dist(Q):
            dd = np.linalg.norm(Q[:, :, None] - Q[:, None, :], axis=-1)
            dd[:, same] = np.nan
            return dd

        dd = opp_dist(P)
        with np.errstate(all="ignore"), warnings.catch_warnings():
            warnings.simplefilter("ignore", RuntimeWarning)
            d_opp = np.nanmin(np.where(np.isnan(dd), np.inf, dd), axis=2)
            d_opp[np.isinf(d_opp)] = np.nan
            n_opp = (np.nan_to_num(dd, nan=np.inf) < PRESSURE_M).sum(2).astype(np.float32)
            dd1 = opp_dist(match.players[at(f - FPS), :, :2] * m)
            d_opp1 = np.nanmin(np.where(np.isnan(dd1), np.inf, dd1), axis=2)
            d_opp1[np.isinf(d_opp1)] = np.nan
            closing = d_opp - d_opp1                              # < 0: being closed down
            cent = np.stack([np.nanmean(np.where((team == g)[None, :, None], P, np.nan), axis=1)
                             for g in (0, 1)], axis=1)            # (F, 2, 2)
        d_centroid = np.linalg.norm(P - cent[:, team], axis=-1)
        n_tracked = np.broadcast_to(tracked.sum(1, keepdims=True).astype(np.float32), d_ball.shape)

        r_ball_team = np.full(d_ball.shape, np.nan, dtype=np.float32)
        for g in (0, 1):
            cols = team == g
            r_ball_team[:, cols] = _rank(d_ball[:, cols])
        cols = [d_ball, rel_v, ball_speed, match.players[f, :, 2],
                d_last, np.broadcast_to(t_since[:, None], d_ball.shape), d_next,
                np.broadcast_to(t_until[:, None], d_ball.shape), d_at_last, d_at_next,
                d_opp, n_opp, closing, d_centroid, n_tracked,
                _rank(d_ball), r_ball_team, _rank(d_last), _rank(d_next), _rank(d_at_last),
                _rank(d_at_next), _rank(d_opp)]
        stack = np.stack([np.asarray(c, dtype=np.float32) for c in cols], axis=-1)
        fi, si = np.nonzero(tracked)
        out.append(stack[fi, si])
        rows_f.append(f[fi])
        rows_s.append(si)
    if not out:
        return np.zeros((0, len(FEATURES)), np.float32), np.zeros(0, int), np.zeros(0, int)
    return np.concatenate(out), np.concatenate(rows_f), np.concatenate(rows_s)


def training_rows(clean, seen):
    carrier = labels(clean, seen)
    keep = graded_mask(clean) & (clean.labels != X)
    keep &= (np.arange(clean.n_frames) % SUBSAMPLE) == 0
    X_, f, s = features(seen, np.flatnonzero(keep))
    return X_, (carrier[f] == s).astype(np.int8)


def fit(rows):
    import lightgbm as lgb
    X_ = np.concatenate([r[0] for r in rows])
    y = np.concatenate([r[1] for r in rows])
    return lgb.train(LGB_PARAMS, lgb.Dataset(X_, y, feature_name=list(FEATURES)), ROUNDS)


def train():
    from bench.__main__ import load_degraded, match_paths
    from bench.match import Match
    paths = match_paths(["dfl", "metrica"])
    rows, names = [], []
    for p in paths:
        clean = Match.load(p)
        rows.append(training_rows(clean, load_degraded(p, "hackathon", 0)))
        names.append(clean.name)
        print("  rows", clean.name, len(rows[-1][1]), "positives {:.1%}".format(rows[-1][1].mean()),
              flush=True)
    os.makedirs(LOMO_DIR, exist_ok=True)
    fit(rows).save_model(FULL_MODEL)
    with open(META, "w") as f:
        json.dump({"trained_on": names, "profile": "hackathon", "features": list(FEATURES),
                   "params": LGB_PARAMS, "rounds": ROUNDS}, f, indent=1)
    print("full model ->", os.path.relpath(FULL_MODEL, ROOT), flush=True)
    for i, held in enumerate(names):
        fit(rows[:i] + rows[i + 1:]).save_model(os.path.join(LOMO_DIR, held + ".txt"))
        print("  without", held, flush=True)


def _model_for(match):
    import lightgbm as lgb
    with open(META) as f:
        trained_on = json.load(f)["trained_on"]
    if match.name in trained_on:
        path = os.path.join(LOMO_DIR, match.name + ".txt")
        if not os.path.isfile(path):
            raise IOError("{} was in the carrier training set; run `python -m possession.carrier "
                          "train` to build its held-out model".format(match.name))
        return lgb.Booster(model_file=path)
    return lgb.Booster(model_file=FULL_MODEL)


_CACHE = {}  # M2 training recomputes features for every fit; the carrier pass is the slow part


def probabilities(match):
    """(T, S) float32 P(slot is the carrier) on graded frames; NaN on untracked slots / elsewhere.

    Cached by match name and tracking content (not slot_team: the scores ignore teams, so a
    home/away swap reuses them)."""
    import hashlib
    key = (match.name, hashlib.sha1(match.ball.tobytes()).hexdigest(),
           hashlib.sha1(match.players.tobytes()).hexdigest())
    if key not in _CACHE:
        if len(_CACHE) > 32:
            _CACHE.clear()
        out = np.full(match.players.shape[:2], np.nan, dtype=np.float32)
        X_, f, s = features(match, np.flatnonzero(graded_mask(match)))
        if len(f):
            out[f, s] = _model_for(match).predict(X_)
        _CACHE[key] = out
    return _CACHE[key]


def team_probabilities(match, probs=None):
    """(T, 3) P(home carrier), P(away carrier), P(nobody).

    ponytail: independent per-slot scores, rescaled so they sum to at most 1 per frame; a
    within-frame softmax (ranking objective) would be the principled upgrade.
    """
    probs = probabilities(match) if probs is None else probs
    p = np.nan_to_num(probs)
    home = p[:, match.slot_team == 0].sum(1)
    away = p[:, match.slot_team == 1].sum(1)
    scale = np.maximum(home + away, 1.0)
    home, away = home / scale, away / scale
    return np.stack([home, away, 1.0 - home - away], axis=1)


M2_FEATURES = ("carrier_home", "carrier_away", "carrier_none", "carrier_diff_05", "carrier_diff_2",
               "carrier_last_team", "carrier_since", "carrier_next_team", "carrier_until")
SURE = 0.5


def frame_features(match):
    """Per-frame features for M2 (team as +1 home / -1 away / 0 none; times in s, capped)."""
    from .features import rolling_nanmean
    from .touches import _last_next
    tp = team_probabilities(match)
    graded = graded_mask(match)
    tp[~graded] = np.nan
    diff = tp[:, 0] - tp[:, 1]
    out = {"carrier_home": tp[:, 0], "carrier_away": tp[:, 1], "carrier_none": tp[:, 2],
           "carrier_diff_05": rolling_nanmean(diff, int(0.5 * FPS) | 1),
           "carrier_diff_2": rolling_nanmean(diff, 2 * FPS + 1)}
    sure = np.nan_to_num(np.maximum(tp[:, 0], tp[:, 1])) > SURE
    f = np.flatnonzero(sure)
    (out["carrier_last_team"], out["carrier_since"], out["carrier_next_team"],
     out["carrier_until"]) = _last_next(f, np.sign(diff[f]), match.n_frames)
    return out


