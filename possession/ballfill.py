"""Ball filling: where the ball is while the tracker has lost it, with an error radius.

Training examples are free: the degrader cuts realistic gaps into clean open-data tracking, and
the clean data still holds the true ball. The model predicts the CORRECTION to the straight line
between where the ball was last and will next be seen, from what the players do meanwhile:
where the likely carrier is (carrier.py), where nearby players run (they converge on the ball),
where the teams stand. A second model predicts the size of its error, so downstream code knows
when to trust the filled ball.

    uv run python -m possession.ballfill train        # models/ballfill/full_{x,y,err}.txt + lomo/
    fill(match) -> (xy (T, 2) normalised, err_m (T,)); seen frames keep the tracked ball, err 0
    finetune(match)   # last step on the hackathon match: hide its visible ball, keep boosting

Base training is open data only; the hackathon match is never the base, only fine-tuning.
"""

import json
import os
import warnings

import numpy as np

from bench import ROOT
from bench.match import FPS, graded_mask

from .context import CAP_S, _bfill_index, _ffill_index

MODEL_DIR = os.environ.get("MTAH_BALLFILL_DIR") or os.path.join(ROOT, "models", "ballfill")
LOMO_DIR = os.path.join(MODEL_DIR, "lomo")  # gitignored, regenerated by `train`
META = os.path.join(MODEL_DIR, "meta.json")
SUBSAMPLE = 3
NEAR_M = 15.0
# L1: the ball often sits still in a gap (set pieces, a player standing on it); squared error
# chases the long-gap outliers and blurs those. The radius is an 80% upper quantile.
RADIUS_Q = 0.8
LGB_PARAMS = dict(objective="regression_l1", learning_rate=0.05, num_leaves=63,
                  min_data_in_leaf=100, feature_fraction=0.8, lambda_l2=1.0, verbose=-1, seed=0,
                  deterministic=True, force_row_wise=True, num_threads=4)
ROUNDS = 400
FINETUNE_ROUNDS = 100
FEATURES = ("t_since", "t_until", "frac", "gap_s", "ix", "iy", "lx", "ly", "nx", "ny",
            "lvx", "lvy", "nvx", "nvy",
            "cx", "cy", "c_mass", "tx", "ty", "t_p",
            "gx", "gy", "hx", "hy", "ax", "ay",
            "n1x", "n1y", "n1_d", "n2x", "n2y", "n_near5", "conv_vx", "conv_vy", "fast_x", "fast_y")
PARTS = ("x", "y", "err")


def _half_bounds(match):
    first = np.zeros(match.n_frames, dtype=np.int64)
    last = np.full(match.n_frames, match.n_frames - 1, dtype=np.int64)
    for _, a, b in match.halves:
        first[a:b + 1], last[a:b + 1] = a, b
    return first, last


def gap_frames(match):
    """Graded frames with no tracked ball but a sighting before or after in the same half."""
    seen = ~np.isnan(match.ball[:, 0])
    first, last_ok = _half_bounds(match)
    last = _ffill_index(seen)
    nxt = _bfill_index(seen)
    ok = (last >= first) | (nxt <= last_ok)
    return np.flatnonzero(graded_mask(match) & ~seen & ok)


def features(match, frames, cprobs=None):
    """(len(frames), len(FEATURES)) float32; positions in metres, relative to nothing (raw)."""
    from . import carrier
    m = np.asarray(match.pitch, dtype=np.float32)
    n = match.n_frames
    ball = match.ball[:, :2] * m
    seen = ~np.isnan(ball[:, 0])
    first, last_ok = _half_bounds(match)
    last = _ffill_index(seen)
    last = np.where(last >= first, last, -1)
    nxt = _bfill_index(seen)
    nxt = np.where(nxt <= last_ok, nxt, n)
    f = frames
    lf, nf = last[f], nxt[f]
    has_l, has_n = lf >= 0, nf < n
    L = np.where(has_l[:, None], ball[np.clip(lf, 0, n - 1)], np.nan)
    N_ = np.where(has_n[:, None], ball[np.clip(nf, 0, n - 1)], np.nan)
    t_since = np.where(has_l, (f - lf) / FPS, CAP_S).clip(0, CAP_S)
    t_until = np.where(has_n, (nf - f) / FPS, CAP_S).clip(0, CAP_S)
    frac = np.where(has_l & has_n, (f - lf) / np.maximum(nf - lf, 1), np.where(has_l, 0.0, 1.0))
    I = np.where((has_l & has_n)[:, None], L + frac[:, None] * (N_ - L),
                 np.where(has_l[:, None], L, N_))

    def ball_vel(idx, sign):
        a = np.clip(idx, 0, n - 1)
        b = np.clip(idx - sign * 3, 0, n - 1)   # 3 frames on the tracked side of the sighting
        v = (ball[a] - ball[b]) * sign * FPS / 3.0
        return v

    lv = np.where(has_l[:, None], ball_vel(lf, 1), np.nan)      # velocity arriving at last sighting
    nv = np.where(has_n[:, None], ball_vel(nf, -1), np.nan)     # velocity leaving next sighting

    P = match.players[f, :, :2] * m
    k = 2
    V = (match.players[np.clip(f + k, 0, n - 1), :, :2] -
         match.players[np.clip(f - k, 0, n - 1), :, :2]) * m * FPS / (2 * k)
    cp = carrier.probabilities(match) if cprobs is None else cprobs
    pc = np.nan_to_num(cp[f])
    mass = pc.sum(1)
    with np.errstate(all="ignore"), warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        C = (np.nan_to_num(P) * pc[..., None]).sum(1) / mass[:, None]
        C[mass < 1e-6] = np.nan
        top = np.argmax(pc, axis=1)
        T_ = P[np.arange(len(f)), top]
        team = match.slot_team
        G = np.nanmean(P, axis=1)
        Hc = np.nanmean(np.where((team == 0)[None, :, None], P, np.nan), axis=1)
        Ac = np.nanmean(np.where((team == 1)[None, :, None], P, np.nan), axis=1)
        d = np.linalg.norm(P - I[:, None], axis=-1)
        dd = np.where(np.isnan(d), np.inf, d)
        o = np.argsort(dd, axis=1)
        n1 = P[np.arange(len(f)), o[:, 0]] - I
        n2 = P[np.arange(len(f)), o[:, 1]] - I if P.shape[1] > 1 else np.full_like(n1, np.nan)
        n1_d = dd[np.arange(len(f)), o[:, 0]]
        n1_d[np.isinf(n1_d)] = np.nan
        near5 = (dd < 5).sum(1).astype(np.float32)
        near = (dd < NEAR_M)[..., None]
        conv = np.nanmean(np.where(near, V, np.nan), axis=1)
        speed = np.linalg.norm(V, axis=-1)
        fast_i = np.argsort(-np.nan_to_num(speed, nan=-1), axis=1)[:, :4]
        fast = np.nanmean(P[np.arange(len(f))[:, None], fast_i], axis=1)
    rel = lambda Q: Q - I  # noqa: E731  positions relative to the interpolated point
    cols = [t_since, t_until, frac, (np.where(has_l & has_n, nf - lf, 0)) / FPS,
            I[:, 0], I[:, 1], *rel(L).T, *rel(N_).T, *lv.T, *nv.T,
            *rel(C).T, mass, *rel(T_).T, pc[np.arange(len(f)), top],
            *rel(G).T, *rel(Hc).T, *rel(Ac).T, *n1.T, n1_d, *n2.T, near5, *conv.T, *rel(fast).T]
    return np.stack([np.asarray(c, dtype=np.float32) for c in cols], axis=1), I


def training_rows(clean, seen):
    frames = gap_frames(seen)
    frames = frames[~np.isnan(clean.ball[frames, 0])]   # truth exists (Metrica lacks it when dead)
    frames = frames[::SUBSAMPLE]
    X_, I = features(seen.without_labels(), frames)
    truth = clean.ball[frames, :2] * np.asarray(clean.pitch, dtype=np.float32)
    return X_, truth - I


def _fit(X_, y, init=None, rounds=ROUNDS, **extra):
    import lightgbm as lgb
    return lgb.train(dict(LGB_PARAMS, **extra), lgb.Dataset(X_, y, feature_name=list(FEATURES)),
                     rounds, init_model=init, keep_training_booster=True)


def _fit_radius(X_, resid, init=None, rounds=ROUNDS):
    return _fit(X_, resid, init, rounds, objective="quantile", alpha=RADIUS_Q)


def fit(rows):
    """{x, y, err} boosters. The radius model learns OUT-OF-FOLD residuals (two halves of the
    matches, each predicted by models fitted on the other), so it sees honest errors."""
    X_ = np.concatenate([r[0] for r in rows])
    R = np.concatenate([r[1] for r in rows])
    bx, by = _fit(X_, R[:, 0]), _fit(X_, R[:, 1])
    fold = np.concatenate([np.full(len(r[1]), i % 2) for i, r in enumerate(rows)])
    resid = np.empty(len(R))
    for k in (0, 1):
        tr, te = fold != k, fold == k
        fx, fy = _fit(X_[tr], R[tr, 0]), _fit(X_[tr], R[tr, 1])
        resid[te] = np.hypot(R[te, 0] - fx.predict(X_[te]), R[te, 1] - fy.predict(X_[te]))
    return {"x": bx, "y": by, "err": _fit_radius(X_, resid)}


def _save(models, prefix):
    for k in PARTS:
        models[k].save_model(prefix + "_" + k + ".txt")


def train():
    from bench.__main__ import load_degraded, match_paths
    from bench.match import Match
    rows, names = [], []
    for p in match_paths(["dfl", "metrica"]):
        clean = Match.load(p)
        rows.append(training_rows(clean, load_degraded(p, "hackathon", 0)))
        names.append(clean.name)
        print("  rows", clean.name, len(rows[-1][1]), flush=True)
    os.makedirs(LOMO_DIR, exist_ok=True)
    _save(fit(rows), os.path.join(MODEL_DIR, "full"))
    with open(META, "w") as f:
        json.dump({"trained_on": names, "profile": "hackathon", "features": list(FEATURES),
                   "params": LGB_PARAMS, "rounds": ROUNDS}, f, indent=1)
    print("full model ->", os.path.relpath(MODEL_DIR, ROOT), flush=True)
    for i, held in enumerate(names):
        _save(fit(rows[:i] + rows[i + 1:]), os.path.join(LOMO_DIR, held))
        print("  without", held, flush=True)


def _models_for(match):
    import lightgbm as lgb
    with open(META) as f:
        meta = json.load(f)
    if match.name in meta["trained_on"]:
        prefix = os.path.join(LOMO_DIR, match.name)
    elif meta.get("finetuned_on") == match.name:
        prefix = os.path.join(MODEL_DIR, "finetuned")
    else:
        prefix = os.path.join(MODEL_DIR, "full")
    return {k: lgb.Booster(model_file=prefix + "_" + k + ".txt") for k in PARTS}


def fill(match, cprobs=None):
    """(xy (T, 2) normalised, err_m (T,)). Tracked frames: the tracked ball, error 0. Gap frames:
    the filled ball and its predicted error. Elsewhere (no sighting in the half): NaN."""
    m = np.asarray(match.pitch, dtype=np.float32)
    xy = match.ball[:, :2].copy()
    err = np.where(np.isnan(xy[:, 0]), np.nan, 0.0).astype(np.float32)
    frames = gap_frames(match)
    if len(frames):
        X_, I = features(match, frames, cprobs)
        md = _models_for(match)
        pred = I + np.stack([md["x"].predict(X_), md["y"].predict(X_)], axis=1)
        xy[frames] = np.clip(pred / m, -0.05, 1.05)
        err[frames] = np.maximum(md["err"].predict(X_), 0.0)
    return xy, err


def finetune(match, seed=0, extra_missing=0.25):
    """Last step, on the hackathon match (no labels used): hide part of its VISIBLE ball in
    gap-shaped spans, then continue boosting the base models on recovering it. Saves
    models/ballfill/finetuned_*.txt, used for that match only. Run it locally."""
    from dataclasses import replace
    from bench.degrade import Profile, _ball_gaps
    rng = np.random.default_rng(seed)
    already = np.isnan(match.ball[:, 0])
    hide = _ball_gaps(match, Profile(ball_missing_alive=extra_missing + already.mean(),
                                     ball_missing_dead=extra_missing + already.mean()), rng)
    hide &= ~already
    masked = replace(match, ball=np.where(hide[:, None], np.nan, match.ball).astype(np.float32))
    frames = np.flatnonzero(hide & graded_mask(match))[::SUBSAMPLE]
    X_, I = features(masked.without_labels(), frames)
    truth = match.ball[frames, :2] * np.asarray(match.pitch, dtype=np.float32)
    R = truth - I
    import lightgbm as lgb
    base = {k: lgb.Booster(model_file=os.path.join(MODEL_DIR, "full_" + k + ".txt"))
            for k in PARTS}
    bx = _fit(X_, R[:, 0], init=base["x"], rounds=FINETUNE_ROUNDS)
    by = _fit(X_, R[:, 1], init=base["y"], rounds=FINETUNE_ROUNDS)
    resid = np.hypot(R[:, 0] - bx.predict(X_), R[:, 1] - by.predict(X_))
    # ponytail: in-sample residuals on the hackathon rows; out-of-fold by time blocks if needed
    be = _fit_radius(X_, resid, init=base["err"], rounds=FINETUNE_ROUNDS)
    _save({"x": bx, "y": by, "err": be}, os.path.join(MODEL_DIR, "finetuned"))
    with open(META) as f:
        meta = json.load(f)
    meta["finetuned_on"] = match.name
    with open(META, "w") as f:
        json.dump(meta, f, indent=1)
    print("fine-tuned on {} hidden frames of {} (aggregate only)".format(len(frames), match.name))


if __name__ == "__main__":
    import sys
    if sys.argv[1:] == ["train"]:
        train()
    else:
        sys.exit("usage: python -m possession.ballfill train")
