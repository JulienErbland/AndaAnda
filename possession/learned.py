"""M2: LightGBM per-frame P(H, A, D) from context features, decoded by the M1 Viterbi.

    MTAH_MODEL_DIR=models/R uv run python -m possession.learned train --features restart
    MTAH_DFL_LABELS=hackathon MTAH_MODEL_DIR=models/B uv run python -m possession.learned train --features touch
        # each: <dir>/lgbm.txt + <dir>/lomo/*.txt; models/ensemble.json combines them (submission)

Trained on degraded DFL (hackathon profile), with every match also seen with home and away
swapped (teams and labels), so the model cannot learn "home usually has it" and has twice the
data. Deterministic: fixed seed, row-wise, fixed thread count.

Leak guard: `predict` on a match that was in the training set uses the leave-one-match-out
model that never saw it, so bench numbers on DFL are always held-out.
"""

import argparse
import json
import os
import sys
from dataclasses import dataclass, replace

import numpy as np

from bench import ROOT, reception
from bench.match import FPS, A, D, H, X, graded_mask

from . import context, hmm

# MTAH_MODEL_DIR points experiments elsewhere (e.g. models_exp/touch) without touching models/.
MODEL_DIR = os.environ.get("MTAH_MODEL_DIR") or os.path.join(ROOT, "models")
# base: context.py; touch: + possession/touches.py; carrier: touch + possession/carrier.py;
# restart: touch + possession/restarts.py
FEATURE_SETS = ("base", "touch", "carrier", "restart")
FULL_MODEL = os.path.join(MODEL_DIR, "lgbm.txt")
META = os.path.join(MODEL_DIR, "lgbm.json")
LOMO_DIR = os.path.join(MODEL_DIR, "lomo")  # gitignored, regenerated by `train`
SUBSAMPLE = 3  # consecutive frames are near-duplicates
LGB_PARAMS = dict(objective="multiclass", num_class=3, learning_rate=0.05, num_leaves=31,
                  min_data_in_leaf=200, feature_fraction=0.8, lambda_l2=1.0, verbose=-1,
                  seed=0, deterministic=True, force_row_wise=True, num_threads=4)
ROUNDS = 300
CLASS_OF = {H: 0, A: 1, D: 2}


@dataclass(frozen=True)
class Params:
    # switch: chosen on the DFL bench only for models/ensemble.json (LightGBM R + B1 and the
    # temporal CNNs TR + TB1, 1/4 each; iteration 3, Oct 31): the best of the seed 0-2 curve,
    # confirmed on fresh seeds 3-5. PFF and the public window are reported only; the real rate
    # (3.32) is a range check against 3.2-7.6 changes per live minute (docs/results.md).
    weight: float = 1.0           # lambda: per-frame log-probability weight
    switch: float = 40.0
    stop: float = 40.0
    restart: float = 40.0
    # Cheaper switch into a team within touch_window_s of one of its detected touches
    # (possession/touches.py), so short possessions that start with a touch are affordable.
    # None: off (constant switch).
    switch_touch: float = None
    touch_window_s: float = 0.5
    touch_kinds: tuple = ("control",)
    # A half is dead until its kick-off when it is not graded from it (restarts.kickoff_frames):
    # the real second half is graded ~2 min before kick-off, all D.
    kickoff_dead: bool = True
    # Keep each predicted restart dead until the first reception (bench/reception.py), for a
    # ground truth that ends stoppages there rather than at the kick like DFL. 2 m (1.5 m on the
    # clean labels) for the noisy tracking; 3 s is about the 90th percentile of DFL's reception
    # delay. None: off. Off until the convention is settled (docs/results.md, Oct 30).
    reception_m: float = None
    reception_s: float = 3.0


def swap_teams(match):
    labels = None
    if match.labels is not None:
        labels = match.labels.copy()
        labels[match.labels == H], labels[match.labels == A] = A, H
    return replace(match, slot_team=(1 - match.slot_team).astype(np.int8), labels=labels)


def frame_features(match, feature_set="base"):
    feats = context.compute(match)
    if feature_set in ("touch", "carrier", "restart"):
        from . import touches
        feats.update(touches.features(match))
    if feature_set == "restart":
        from . import restarts
        feats.update(restarts.features(match))
    if feature_set == "carrier":
        # carrier picks its held-out model by match name, so training rows are out-of-fold
        from . import carrier
        feats.update(carrier.frame_features(match))
    return feats


def training_rows(match, feature_set="base"):
    X_, names = context.matrix(frame_features(match.without_labels(), feature_set))
    keep = graded_mask(match) & (match.labels != X)
    keep &= (np.arange(match.n_frames) % SUBSAMPLE) == 0
    y = np.vectorize(CLASS_OF.get)(match.labels[keep])
    return X_[keep], y, names


def fit(matches, feature_set="base"):
    return fit_rows([training_rows(v, feature_set) for m in matches for v in (m, swap_teams(m))])


def fit_rows(rows, extra=(), extra_weight=1.0):
    """LightGBM on row groups [(X, y, names)]; `extra` groups (self-training) get extra_weight."""
    import lightgbm as lgb
    groups = list(rows) + list(extra)
    X_ = np.concatenate([r[0] for r in groups])
    y = np.concatenate([r[1] for r in groups])
    w = None
    if extra:
        w = np.concatenate([np.full(len(r[1]), 1.0) for r in rows]
                           + [np.full(len(r[1]), extra_weight) for r in extra])
    return lgb.train(LGB_PARAMS, lgb.Dataset(X_, y, weight=w, feature_name=groups[0][2]), ROUNDS)


N_FOLDS = 5   # PFF (64 matches) is held out by fold; every other match by itself


def groups_of(names):
    """{name: held-out group}: PFF matches in N_FOLDS fixed folds (sorted id), others alone."""
    pff = sorted(n for n in names if n.startswith("pff-"))
    g = {n: "pff-fold{}".format(i % N_FOLDS) for i, n in enumerate(pff)}
    g.update({n: n for n in names if not n.startswith("pff-")})
    return g


def _rows_job(args):
    """Worker: load, degrade and featurise one (path, draw) -> (name, rows for m and its swap)."""
    path, k, profile, spread, feature_set, dead_mix = args
    from bench.__main__ import load_degraded
    from bench.degrade import PROFILES, degrade, vary
    from bench.match import Match
    if k == 0 and spread == 0:
        m = load_degraded(path, profile, 0)
    else:
        clean = Match.load(path)
        prof = profile
        if clean.name.startswith("pff-") and profile == "hackathon":
            prof = "pff"
        if spread > 0:
            prof = vary(prof, np.random.default_rng(1000 + k + sum(map(ord, clean.name))), spread)
        if dead_mix and k % 2 == 1:     # odd draws: the dead ball parked (DFL / PFF-like)
            prof = replace(PROFILES[prof] if isinstance(prof, str) else prof, dead_ball_moves=False)
        m = degrade(clean, prof, seed=k + sum(map(ord, clean.name)))
    return m.name, [training_rows(v, feature_set) for v in (m, swap_teams(m))]


def train(feature_set="base", draws=1, spread=0.0, profile="hackathon", with_pff=False, workers=4,
          with_metrica=False, self_train=0.0, dead_mix=False, self_train_mode="control", train_k=0):
    """Full model + one held-out model per group (groups_of). Each match's rows are computed once,
    in parallel, and reused by every fit. draws > 1: each match enters `draws` times, each with its
    own degrader seed and, when spread > 0, its own random neighbour of the profile (degrade.vary).
    train_k > 0 (learning curve, DFL only): the full model fits the first k matches (sorted), each
    held-out model the k matches that follow its own, cyclically."""
    from multiprocessing import Pool
    from bench.__main__ import match_paths
    paths = match_paths(["dfl"] + (["pff"] if with_pff else []) + (["metrica"] if with_metrica else []))
    jobs = [(p, k, profile, spread, feature_set, dead_mix) for p in paths for k in range(draws)]
    rows = {}
    with Pool(workers) as pool:
        for i, (name, r) in enumerate(pool.imap(_rows_job, jobs)):
            rows.setdefault(name, []).extend(r)
            if (i + 1) % 10 == 0 or i + 1 == len(jobs):
                print("  rows {}/{}".format(i + 1, len(jobs)), flush=True)
    groups = groups_of(rows)
    extra = ()
    if self_train > 0:   # real-match rows (possession/selftrain.py) join every fit
        from . import selftrain
        extra = selftrain.rows(selftrain.real_match(), feature_set, mode=self_train_mode)
    os.makedirs(LOMO_DIR, exist_ok=True)
    names = sorted(rows)
    if train_k:
        assert not with_pff and not with_metrica and train_k < len(names)
    keep = {g: names[:train_k] if g is None else
            [names[(names.index(g) + 1 + i) % len(names)] for i in range(train_k)]
            for g in [None] + names} if train_k else None
    fit_rows([x for n, r in rows.items() if keep is None or n in keep[None] for x in r], extra,
             self_train).save_model(FULL_MODEL)
    with open(META, "w") as f:
        json.dump({"trained_on": sorted(rows), "groups": groups, "profile": profile,
                   "feature_set": feature_set, "draws": draws, "spread": spread,
                   "with_pff": with_pff, "with_metrica": with_metrica,
                   "self_train": self_train, "self_train_mode": self_train_mode,
                   "dead_mix": dead_mix, "train_k": train_k, "params": LGB_PARAMS,
                   "rounds": ROUNDS}, f, indent=1)
    print("full model ->", os.path.relpath(FULL_MODEL, ROOT), flush=True)
    for g in sorted(set(groups.values())):
        fit_rows([x for n, r in rows.items() if groups[n] != g and (keep is None or n in keep[g])
                  for x in r], extra,
                 self_train).save_model(os.path.join(LOMO_DIR, g + ".txt"))
        print("  without", g, flush=True)


def _meta(model_dir):
    with open(os.path.join(model_dir, "lgbm.json")) as f:
        return json.load(f)


def _model_for(match, model_dir=None):
    import lightgbm as lgb
    model_dir = model_dir or MODEL_DIR
    meta = _meta(model_dir)
    if match.name in meta["trained_on"]:
        group = meta.get("groups", {}).get(match.name, match.name)
        path = os.path.join(model_dir, "lomo", group + ".txt")
        if not os.path.isfile(path):
            raise IOError("{} was in the training set; run `python -m possession.learned train` "
                          "to build its held-out model".format(match.name))
        return lgb.Booster(model_file=path)
    return lgb.Booster(model_file=os.path.join(model_dir, "lgbm.txt"))


def _single(match, model_dir, cache):
    """P(H, A, D) of one trained model dir; feature matrices shared through `cache`."""
    if os.path.isfile(os.path.join(model_dir, "tcn.json")):   # iteration 2's temporal CNN
        from . import tcn
        return tcn.predict(match, model_dir, cache)
    fs = _meta(model_dir).get("feature_set", "base")
    if fs not in cache:
        cache[fs] = context.matrix(frame_features(match, fs))[0]
    return _model_for(match, model_dir).predict(cache[fs])


def members(model_dir=None):
    """[(member dir, weight)]: the members of an ensemble dir (`ensemble.json`, dirs relative to
    the repo), or [(model_dir, 1.0)] for a single trained model."""
    model_dir = model_dir or MODEL_DIR
    ens = os.path.join(model_dir, "ensemble.json")
    if not os.path.isfile(ens):
        return [(model_dir, 1.0)]
    with open(ens) as f:
        return [(os.path.join(ROOT, d), float(w)) for d, w in json.load(f)["members"]]


def probabilities(match, model_dir=None):
    """(T, 3) P(H, A, D); uniform outside the graded halves.

    An ensemble dir gives the weighted geometric mean of its members' probabilities, each member
    held-out on its own training matches."""
    ms, cache = members(model_dir), {}
    if len(ms) == 1:
        return _single(match, ms[0][0], cache)
    logp = sum(w * np.log(np.clip(_single(match, d, cache), 1e-6, 1.0)) for d, w in ms)
    p = np.exp(logp / sum(w for _, w in ms))
    return p / p.sum(1, keepdims=True)


def switch_costs(match, p, touch_list=None):
    """(T, 2) cost of switching into H / A: p.switch, or p.switch_touch near that team's touches."""
    from . import touches
    cost = np.full((match.n_frames, 2), p.switch)
    w = int(round(p.touch_window_s * FPS))
    for t in touches.detect(match) if touch_list is None else touch_list:
        if t.kind in p.touch_kinds:
            cost[max(0, t.frame - w):t.frame + w + 1, t.team] = p.switch_touch
    return cost


def scores(match, p, probs, bonus=None):
    """(T, 3) decoder scores: weighted log-probabilities (+ bonus), kick-off rule applied."""
    out = p.weight * np.log(np.clip(probs, 1e-4, 1.0))
    if bonus is not None:
        out = out + bonus
    if p.kickoff_dead:
        from . import restarts
        for first, kick in restarts.kickoff_frames(match, probs[:, CLASS_OF[D]]):
            out[first:kick, [CLASS_OF[H], CLASS_OF[A]]] = -1e3
    return out


def decode(match, p=Params(), probs=None, bonus=None, touch_list=None):
    """bonus: optional (T, 3) scores added before decoding (e.g. tags.bonus, Smart Tagging).
    touch_list: precomputed touches.detect(match), reused when p.switch_touch is set."""
    probs = probabilities(match) if probs is None else probs
    scores_ = scores(match, p, probs, bonus)
    sw = None if p.switch_touch is None else switch_costs(match, p, touch_list)
    labels = hmm.decode_scores(match, scores_, hmm.Params(switch=p.switch, stop=p.stop,
                                                          restart=p.restart), sw)
    if p.reception_m is None:
        return labels
    return reception.dead_until_reception(match, labels, p.reception_m, p.reception_s)[0]


def predict(match):
    return decode(match)


