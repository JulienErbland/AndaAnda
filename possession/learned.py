"""M2: LightGBM per-frame P(H, A, D) from context features, decoded by the M1 Viterbi.

    uv run python -m possession.learned train      # models/lgbm.txt + models/lomo/*.txt

Trained on degraded DFL (hackathon profile), with every match also seen with home and away
swapped (teams and labels), so the model cannot learn "home usually has it" and has twice the
data. Deterministic: fixed seed, row-wise, fixed thread count.

Leak guard: `predict` on a match that was in the training set uses the leave-one-match-out
model that never saw it, so bench numbers on DFL are always held-out.
"""

import argparse
import json
import os
import sys
from dataclasses import dataclass, replace

import numpy as np

from bench import ROOT
from bench.match import A, D, H, X, graded_mask

from . import context, hmm

# MTAH_MODEL_DIR points experiments elsewhere (e.g. models_exp/touch) without touching models/.
MODEL_DIR = os.environ.get("MTAH_MODEL_DIR") or os.path.join(ROOT, "models")
# base: context.py; touch: + possession/touches.py; carrier: touch + possession/carrier.py
FEATURE_SETS = ("base", "touch", "carrier")
FULL_MODEL = os.path.join(MODEL_DIR, "lgbm.txt")
META = os.path.join(MODEL_DIR, "lgbm.json")
LOMO_DIR = os.path.join(MODEL_DIR, "lomo")  # gitignored, regenerated by `train`
SUBSAMPLE = 3  # consecutive frames are near-duplicates
LGB_PARAMS = dict(objective="multiclass", num_class=3, learning_rate=0.05, num_leaves=31,
                  min_data_in_leaf=200, feature_fraction=0.8, lambda_l2=1.0, verbose=-1,
                  seed=0, deterministic=True, force_row_wise=True, num_threads=4)
ROUNDS = 300
CLASS_OF = {H: 0, A: 1, D: 2}


@dataclass(frozen=True)
class Params:
    # Chosen with scripts/tune_learned.py (Oct 20): DFL held-out spellF1 is flat for switch 3-10
    # (0.522-0.527); 10 gives 4.16 possessions per live minute on the full hackathon match,
    # closest to the 4.25 seen in the public window.
    weight: float = 1.0           # lambda: per-frame log-probability weight
    switch: float = 10.0
    stop: float = 40.0
    restart: float = 40.0


def swap_teams(match):
    labels = None
    if match.labels is not None:
        labels = match.labels.copy()
        labels[match.labels == H], labels[match.labels == A] = A, H
    return replace(match, slot_team=(1 - match.slot_team).astype(np.int8), labels=labels)


def frame_features(match, feature_set="base"):
    feats = context.compute(match)
    if feature_set in ("touch", "carrier"):
        from . import touches
        feats.update(touches.features(match))
    if feature_set == "carrier":
        # carrier picks its held-out model by match name, so training rows are out-of-fold
        from . import carrier
        feats.update(carrier.frame_features(match))
    return feats


def training_rows(match, feature_set="base"):
    X_, names = context.matrix(frame_features(match.without_labels(), feature_set))
    keep = graded_mask(match) & (match.labels != X)
    keep &= (np.arange(match.n_frames) % SUBSAMPLE) == 0
    y = np.vectorize(CLASS_OF.get)(match.labels[keep])
    return X_[keep], y, names


def fit(matches, feature_set="base"):
    return fit_rows([training_rows(v, feature_set) for m in matches for v in (m, swap_teams(m))])


def fit_rows(rows):
    import lightgbm as lgb
    X_ = np.concatenate([r[0] for r in rows])
    y = np.concatenate([r[1] for r in rows])
    return lgb.train(LGB_PARAMS, lgb.Dataset(X_, y, feature_name=rows[0][2]), ROUNDS)


N_FOLDS = 5   # PFF (64 matches) is held out by fold; every other match by itself


def groups_of(names):
    """{name: held-out group}: PFF matches in N_FOLDS fixed folds (sorted id), others alone."""
    pff = sorted(n for n in names if n.startswith("pff-"))
    g = {n: "pff-fold{}".format(i % N_FOLDS) for i, n in enumerate(pff)}
    g.update({n: n for n in names if not n.startswith("pff-")})
    return g


def _rows_job(args):
    """Worker: load, degrade and featurise one (path, draw) -> (name, rows for m and its swap)."""
    path, k, profile, spread, feature_set = args
    from bench.__main__ import load_degraded
    from bench.degrade import degrade, vary
    from bench.match import Match
    if k == 0 and spread == 0:
        m = load_degraded(path, profile, 0)
    else:
        clean = Match.load(path)
        prof = profile
        if clean.name.startswith("pff-") and profile == "hackathon":
            prof = "pff"
        if spread > 0:
            prof = vary(prof, np.random.default_rng(1000 + k + sum(map(ord, clean.name))), spread)
        m = degrade(clean, prof, seed=k + sum(map(ord, clean.name)))
    return m.name, [training_rows(v, feature_set) for v in (m, swap_teams(m))]


def train(feature_set="base", draws=1, spread=0.0, profile="hackathon", with_pff=False, workers=4):
    """Full model + one held-out model per group (groups_of). Each match's rows are computed once,
    in parallel, and reused by every fit. draws > 1: each match enters `draws` times, each with its
    own degrader seed and, when spread > 0, its own random neighbour of the profile (degrade.vary)."""
    from multiprocessing import Pool
    from bench.__main__ import match_paths
    paths = match_paths(["dfl"] + (["pff"] if with_pff else []))
    jobs = [(p, k, profile, spread, feature_set) for p in paths for k in range(draws)]
    rows = {}
    with Pool(workers) as pool:
        for i, (name, r) in enumerate(pool.imap(_rows_job, jobs)):
            rows.setdefault(name, []).extend(r)
            if (i + 1) % 10 == 0 or i + 1 == len(jobs):
                print("  rows {}/{}".format(i + 1, len(jobs)), flush=True)
    groups = groups_of(rows)
    os.makedirs(LOMO_DIR, exist_ok=True)
    fit_rows([x for r in rows.values() for x in r]).save_model(FULL_MODEL)
    with open(META, "w") as f:
        json.dump({"trained_on": sorted(rows), "groups": groups, "profile": profile,
                   "feature_set": feature_set, "draws": draws, "spread": spread,
                   "with_pff": with_pff, "params": LGB_PARAMS, "rounds": ROUNDS}, f, indent=1)
    print("full model ->", os.path.relpath(FULL_MODEL, ROOT), flush=True)
    for g in sorted(set(groups.values())):
        fit_rows([x for n, r in rows.items() if groups[n] != g for x in r]).save_model(
            os.path.join(LOMO_DIR, g + ".txt"))
        print("  without", g, flush=True)


def _model_for(match):
    import lightgbm as lgb
    with open(META) as f:
        meta = json.load(f)
    if match.name in meta["trained_on"]:
        group = meta.get("groups", {}).get(match.name, match.name)
        path = os.path.join(LOMO_DIR, group + ".txt")
        if not os.path.isfile(path):
            raise IOError("{} was in the training set; run `python -m possession.learned train` "
                          "to build its held-out model".format(match.name))
        return lgb.Booster(model_file=path)
    return lgb.Booster(model_file=FULL_MODEL)


def probabilities(match):
    """(T, 3) P(H, A, D); uniform outside the graded halves."""
    with open(META) as f:
        feature_set = json.load(f).get("feature_set", "base")
    X_, _ = context.matrix(frame_features(match, feature_set))
    return _model_for(match).predict(X_)


def decode(match, p=Params(), probs=None, bonus=None):
    """bonus: optional (T, 3) scores added before decoding (e.g. tags.bonus, Smart Tagging)."""
    probs = probabilities(match) if probs is None else probs
    scores = p.weight * np.log(np.clip(probs, 1e-4, 1.0))
    if bonus is not None:
        scores = scores + bonus
    return hmm.decode_scores(match, scores, hmm.Params(switch=p.switch, stop=p.stop,
                                                       restart=p.restart))


def predict(match):
    return decode(match)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["train"])
    ap.add_argument("--features", choices=FEATURE_SETS, default="base")
    ap.add_argument("--draws", type=int, default=1, help="degraded copies per match")
    ap.add_argument("--vary", type=float, default=0.0,
                    help="spread of the degrader parameters per copy (degrade.vary), e.g. 0.25")
    ap.add_argument("--profile", default="hackathon", help="degrader profile (clean = no degradation)")
    ap.add_argument("--with-pff", action="store_true", help="also train on the 64 PFF matches")
    ap.add_argument("--overwrite-submission-model", action="store_true",
                    help="allow experiment options to write into models/ (the submission model)")
    a = ap.parse_args()
    experiment = (a.draws, a.vary, a.profile, a.with_pff) != (1, 0.0, "hackathon", False)
    if experiment and not os.environ.get("MTAH_MODEL_DIR") and not a.overwrite_submission_model:
        sys.exit("refusing to overwrite the submission model in models/ with experiment options; "
                 "set MTAH_MODEL_DIR=models_exp/<name> (or pass --overwrite-submission-model)")
    train(a.features, a.draws, a.vary, a.profile, a.with_pff)
